    local second_language = locale.second_language or ""
    local region = locale.region or "US"

    return {
        Info = {
            Author = "SrTristeSad",
            Description = "Luelement standalone Elementum host",
            Disclaimer = "",
            Fanart = "",
            Home = paths.root,
            Icon = "",
            ID = config.id,
            Name = config.name,
            Path = paths.plugin,
            Profile = paths.profile,
            TempPath = paths.temp,
            Stars = "",
            Summary = "Elementum engine for Luelement",
            Type = "plugin",
            Version = config.version,
            Xbmc = "",
        },
        Platform = {
            OS = platform.os,
            Arch = platform.arch,
            Version = "",
            -- Elementum usa este número apenas para branches internos de
            -- compatibilidade. Não significa que Kodi esteja instalado.
            Kodi = 20,
            Build = "Luelement",
        },
        Settings = default_settings(paths),
        Language = language,
        SecondLanguage = second_language,
        Region = region,
    }
end

